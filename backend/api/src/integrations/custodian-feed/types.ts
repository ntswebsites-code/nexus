/** Custodian-feed adapter contract (GAP-A05). Implementations: `file-drop` (admin upload), `fake`, `live` (SWIFT/API stub). */

export type CustodianFeedMode = 'file-drop' | 'fake' | 'live';

export interface FeedStatement {
  id: string;
  counterpartyId: string;
  accountRef: string;
  /** YYYY-MM-DD */
  statementDate: string;
  currency: string | null;
  closingCash: string | null;
  holdingsMv: string | null;
  tradeCount: number;
  source: string;
}

export interface FeedHolding {
  accountRef: string;
  statementDate: string;
  ticker: string;
  isin?: string | null;
  quantity: string;
  price?: string | null;
  marketValue?: string | null;
  currency: string;
}

export interface FeedTransaction {
  tradeRef: string;
  /** ISO timestamp */
  executionAt: string;
  accountRef: string;
  ticker: string;
  isin?: string | null;
  side: 'BUY' | 'SELL';
  quantity: string;
  price: string;
  currency: string;
  settlementDate?: string | null;
  note?: string | null;
}

export interface ListStatementsQuery {
  counterpartyId?: string;
  accountRef?: string;
  from?: string;
  to?: string;
  limit?: number;
}

/** One statement as read from a file or generated by the fake adapter, before it is stored. */
export interface ParsedStatement {
  format: 'CSV' | 'MT940' | 'JSON';
  accountRef: string;
  statementDate: string;
  currency: string | null;
  closingCash: string | null;
  holdings: FeedHolding[];
  transactions: FeedTransaction[];
  warnings: string[];
}

export interface CustodianFeedAdapter {
  readonly name: CustodianFeedMode;
  listStatements(q?: ListStatementsQuery): Promise<FeedStatement[]>;
  fetchStatement(id: string): Promise<FeedStatement | null>;
  fetchHoldings(statementId: string): Promise<FeedHolding[]>;
  fetchTransactions(statementId: string): Promise<FeedTransaction[]>;
}
